import test from 'node:test';
import assert from 'node:assert/strict';
import { buildReportHtml, escapeHtml, formatReportTime } from '../../frontend/src/lib/report-html.ts';
import { toCSV } from '../../frontend/src/lib/csv-utils.ts';
import { fileSlug } from '../../frontend/src/lib/download.ts';

test('report escapes every value a tool passes in', () => {
  const attack = '<script>alert("x")</script>';
  const html = buildReportHtml({
    title: `Report ${attack}`,
    subject: attack,
    subtitle: attack,
    cards: [{ label: attack, value: attack, meta: attack }],
    sections: [
      { title: attack, meta: attack, rows: [[attack, attack]] },
      { title: 'Table', table: { columns: [attack], rows: [[attack]] } },
      { title: 'List', list: [attack] },
      { title: 'Pills', pills: [attack] },
      { title: 'Text', text: attack },
      { title: 'Note', note: attack },
    ],
  });

  assert.equal(html.includes('<script>'), false);
  assert.ok(html.includes('&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt;'));
});

test('report has the shared frame: brand, title, subject, timestamp and footer', () => {
  const html = buildReportHtml({
    title: 'DNS Snapshot',
    subject: 'example.com',
    checkedAt: '2026-11-26T10:00:00.000Z',
    cards: [{ label: 'Records', value: 12 }],
    sections: [{ title: 'A Records', meta: '2 found', table: { columns: ['Value', 'TTL'], rows: [['192.0.2.1', 300], ['192.0.2.2', 300]], alignRight: [1], mono: [0] } }],
  });

  assert.ok(html.startsWith('<!DOCTYPE html>'));
  assert.ok(html.includes('<title>DNS Snapshot - example.com</title>'));
  assert.ok(html.includes('<h1>DNS Snapshot</h1>'));
  assert.ok(html.includes('Checked at 2026-11-26 10:00:00 UTC'));
  assert.ok(html.includes('Generated by SysAdmin Toolkit'));
  assert.ok(html.includes('<td class="mono">192.0.2.1</td>'));
  assert.ok(html.includes('<td class="right">300</td>'));
  assert.equal(/https?:\/\//.test(html), false, 'report must not load anything from the network');
});

test('report shows placeholders for empty values and empty sections', () => {
  const html = buildReportHtml({
    title: 'Report',
    sections: [
      { title: 'Details', rows: [['Missing', null], ['Flag', true], ['Zero', 0]] },
      { title: 'Empty table', table: { columns: ['A'], rows: [] }, empty: 'No rows here.' },
      { title: 'Empty list', list: [] },
    ],
  });

  assert.ok(html.includes('<td class="mono">—</td>'));
  assert.ok(html.includes('<td class="mono">Yes</td>'));
  assert.ok(html.includes('<td class="mono">0</td>'));
  assert.ok(html.includes('No rows here.'));
  assert.ok(html.includes('None.'));
});

test('helpers: escapeHtml, formatReportTime, toCSV, fileSlug', () => {
  assert.equal(escapeHtml(`a&b<c>"d'`), 'a&amp;b&lt;c&gt;&quot;d&#39;');
  assert.equal(escapeHtml(null), '');
  assert.equal(formatReportTime('not a date'), 'not a date');
  assert.equal(formatReportTime(undefined), '');

  assert.equal(
    toCSV([{ name: 'a "quoted" value', nested: { n: 1 }, list: [1, 2] }, { name: 'b', extra: null }]),
    '"name","nested n","list","extra"\n"a ""quoted"" value","1","[1,2]",""\n"b","","",""',
  );

  assert.equal(fileSlug('10.0.0.0/24'), '10.0.0.0-24');
  assert.equal(fileSlug('2001:db8::1'), '2001-db8-1');
  assert.equal(fileSlug('../../etc/passwd'), 'etc-passwd');
  assert.equal(fileSlug('   '), 'report');
});
